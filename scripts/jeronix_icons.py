# directory -> (context, nominal size)
DIRECTORIES = {"scalable/apps": ("Applications", 128), "scalable/places": ("Places", 128),
               "scalable/mimetypes": ("MimeTypes", 128), "scalable/status": ("Status", 16)}


def index_theme():
    lines = ["[Icon Theme]", f"Name={THEME}",
             "Comment=Original JERONIX icons and Fluent status icons; everything else falls back to Adwaita",
             f"Inherits={','.join(INHERITS)}", "Example=folder",
             f"Directories={','.join(DIRECTORIES)}", ""]
    for directory, (context, size) in DIRECTORIES.items():
        lines += [f"[{directory}]", f"Size={size}", "MinSize=8", "MaxSize=512", "Type=Scalable",
                  f"Context={context}", ""]
    return "\n".join(lines)


def icons(tokens):
    """{relative path: svg text} for the whole theme."""
    c = palette(tokens)
    out = {}
    for name, (title, glyph) in app_glyphs(c).items():
        tile = c["accent"] if name == "io.jeronix.Welcome" else None
        out[f"scalable/apps/{name}.svg"] = svg(app_tile(c, glyph, tile), title)
    for alias, target in APP_ALIASES.items():
        out[f"scalable/apps/{alias}.svg"] = out[f"scalable/apps/{target}.svg"]
    for name, (title, emblem) in place_emblems(c).items():
        out[f"scalable/places/{name}.svg"] = svg(folder(c, emblem), title)
    out["scalable/places/user-trash.svg"] = svg(trash(c, False), "Trash")
    out["scalable/places/user-trash-full.svg"] = svg(trash(c, True), "Trash (full)")
    for name, (title, glyph, band) in mime_glyphs(c).items():
        out[f"scalable/mimetypes/{name}.svg"] = svg(page(c, glyph, band), title)
    for alias, target in MIME_ALIASES.items():
        out[f"scalable/mimetypes/{alias}.svg"] = out[f"scalable/mimetypes/{target}.svg"]
    return out


def build(tokens, out):
    """Writes <out>/icons/JERONIX and the JERONIX app icons into hicolor."""
    theme = Path(out) / "icons" / THEME
    built = []
    for rel, text in {**icons(tokens), **status_icons()}.items():
        path = theme / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        built.append(path)
    (theme / "index.theme").write_text(index_theme(), encoding="utf-8")
    built.append(theme / "index.theme")
    # JERONIX app icons also go to hicolor, so they show with any icon theme.
    for rel, text in icons(tokens).items():
        if rel.startswith("scalable/apps/io.jeronix."):
            path = Path(out) / "icons" / "hicolor" / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            built.append(path)
    return built


