def palette(tokens):
    b = tokens["brand"]
    return {
        "tile": b["graphite"], "glyph": b["ivory"], "accent": b["blue"], "accent2": b["sage"],
        "accent-deep": b["blue-deep"], "seed": b["sage-light"], "paper": b["paper"], "sand": b["sand"],
        "line": tokens["color"]["light"]["border"], "ink": tokens["color"]["light"]["text"],
        "moss": b["moss"],
    }


def svg(body, title):
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            f"<!-- JERONIX icon theme: {title}. Generated by scripts/jeronix_icons.py. "
            "SPDX-License-Identifier: CC-BY-SA-4.0 -->\n"
            '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
            f"{body}\n</svg>\n")


def stroke(d, color, width=STROKE, extra=""):
    return (f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width}" '
            f'stroke-linecap="round" stroke-linejoin="round"{extra}/>')


