"""Builds the jeronix-desktop file tree and Debian package.

The tree is the single definition of what JERONIX adds to an Ubuntu system.
The ISO builder puts it into the image as its own squashfs layer, and the
.deb carries the same files for installing or repairing a system later.
Everything is derived from the repository: design tokens (via
scripts/jeronix_design.py), extensions and the Pure layout (via
scripts/jeronix_layout.py, which validates it against this machine's
installed GSettings schemas).

    packaging/jeronix_payload.py tree OUTDIR [--dconf-profile FILE]
    packaging/jeronix_payload.py deb  OUTDIR [--dconf-profile FILE]
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import jeronix_design as design  # noqa: E402
import jeronix_layout as layout_tool  # noqa: E402

CONFIG = ROOT / "packaging" / "jeronix-desktop.json"
PURE = ROOT / "desktop" / "layouts" / "pure.json"
SYSTEM_DATA = Path("/usr/share")
DCONF_DB = "jeronix"


def load_config():
    return json.loads(CONFIG.read_text(encoding="utf-8"))


def dconf_keyfile(config, layout_path=PURE):
    """System dconf defaults: the validated Pure layout plus the extensions
    JERONIX enables by default. Users can still change every key."""
    layout = layout_tool.load_layout(layout_path)
    changes, skipped = layout_tool.resolve(layout, need_assets=False, data_dir=SYSTEM_DATA)
    if skipped:
        raise SystemExit(f"layout settings skipped on the build host: {skipped}. Build on "
                         "Ubuntu 26.04 desktop so every target schema can be validated.")
    from gi.repository import Gio, GLib
    groups = {}
    for c in changes:
        schema = Gio.SettingsSchemaSource.get_default().lookup(c["schema"], True)
        groups.setdefault(schema.get_path().strip("/"), []).append(f"{c['key']}={c['variant'].print_(False)}")
    extensions = GLib.Variant("as", config["enabled_extensions"]).print_(False)
    groups.setdefault("org/gnome/shell", []).append(f"enabled-extensions={extensions}")
    lines = [f"# JERONIX system defaults: layout {layout['id']} {layout['version']} and default extensions.",
             "# Generated by packaging/jeronix_payload.py. Users override any key normally;",
             "# 'gsettings reset' returns to these values.", ""]
    for group in sorted(groups):
        lines += [f"[{group}]"] + groups[group] + [""]
    return "\n".join(lines)


def dconf_profile(base_profile):
    """The user dconf profile with the JERONIX system database appended.

    base_profile is the profile the Ubuntu image already ships (None if it
    ships none, in which case dconf's implicit default "user-db:user" is
    written out explicitly)."""
    lines = [l for l in (base_profile or "user-db:user\n").splitlines() if l.strip()]
    if f"system-db:{DCONF_DB}" not in lines:
        lines.append(f"system-db:{DCONF_DB}")
    if not lines[0].startswith("user-db:"):
        raise SystemExit("unexpected dconf profile: first line must be the user database")
    return "\n".join(lines) + "\n"


def background_properties(config):
    w = f"/usr/share/{layout_tool.ASSETS['wallpaper-light']}"
    d = f"/usr/share/{layout_tool.ASSETS['wallpaper-dark']}"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE wallpapers SYSTEM "gnome-wp-list.dtd">
<wallpapers>
  <wallpaper deleted="false">
    <name>JERONIX</name>
    <filename>{w}</filename>
    <filename-dark>{d}</filename-dark>
    <options>zoom</options>
    <shade_type>solid</shade_type>
    <pcolor>#1E1D1B</pcolor>
    <scolor>#1E1D1B</scolor>
  </wallpaper>
</wallpapers>
"""


def build_tree(out, base_profile=None):
    """Creates the payload under out/root. Returns the root path."""
    config = load_config()
    root = out / "root"
    if root.exists():
        shutil.rmtree(root)
    assets = out / "assets"
    design.build(assets)

    def put(src, rel):
        dest = root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if Path(src).is_dir():
            shutil.copytree(src, dest)
        else:
            shutil.copyfile(src, dest)
        return dest

    def write(rel, text, mode=0o644):
        dest = root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")
        dest.chmod(mode)
        return dest

    ext = "usr/share/gnome-shell/extensions"
    # Every extension, as built (generated stylesheets, compiled schemas).
    for built in sorted((assets / "extensions").iterdir()):
        put(built, f"{ext}/{built.name}")

    put(assets / "wallpapers" / "jeronix-dark-3840x2160.png", f"usr/share/{layout_tool.ASSETS['wallpaper-dark']}")
    put(assets / "wallpapers" / "jeronix-light-3840x2160.png", f"usr/share/{layout_tool.ASSETS['wallpaper-light']}")
    write("usr/share/gnome-background-properties/jeronix.xml", background_properties(config))
    for icon in sorted((assets / "icons" / "hicolor").rglob("*")):
        if icon.is_file():
            put(icon, f"usr/share/icons/hicolor/{icon.relative_to(assets / 'icons' / 'hicolor')}")
    put(assets / "branding", "usr/share/jeronix/branding")

    # Layout tool and data, runnable on the installed system as jeronix-layout.
    put(ROOT / "scripts" / "jeronix_layout.py", "usr/share/jeronix/scripts/jeronix_layout.py")
    put(ROOT / "config" / "platform.json", "usr/share/jeronix/config/platform.json")
    put(PURE, "usr/share/jeronix/layouts/pure.json")
    write("usr/bin/jeronix-layout",
          "#!/bin/sh\n# JERONIX layout tool: validate, apply and restore desktop layouts.\n"
          "exec python3 /usr/share/jeronix/scripts/jeronix_layout.py \"$@\"\n", 0o755)

    keyfile = write(f"etc/dconf/db/{DCONF_DB}.d/00-jeronix", dconf_keyfile(config))
    subprocess.run(["dconf", "compile", str(root / f"etc/dconf/db/{DCONF_DB}"), str(keyfile.parent)], check=True)
    (root / f"etc/dconf/db/{DCONF_DB}").chmod(0o644)
    write("etc/dconf/profile/user", dconf_profile(base_profile))

    platform = design.load_platform()
    write("etc/jeronix-release",
          f'NAME="JERONIX"\nVERSION="{config["version"]}"\n'
          f'BASE="Ubuntu {platform["ubuntu"]["version"]} ({platform["ubuntu"]["codename"]})"\n'
          f'HOME_URL=""\nSTATUS="pre-release; see /usr/share/doc/jeronix-desktop"\n')
    write("usr/share/doc/jeronix-desktop/copyright",
          "JERONIX desktop layer\n\nCode (extensions, scripts): GPL-3.0-or-later. "
          "See /usr/share/common-licenses/GPL-3.\nArtwork (icons, wallpapers, branding): CC-BY-SA-4.0.\n")
    write("usr/share/doc/jeronix-desktop/README",
          "JERONIX adds a GNOME Shell theme, the Stay Awake Quick Settings toggle, wallpapers,\n"
          "icons and the Pure layout as system defaults to Ubuntu.\n\n"
          "  gnome-extensions disable jeronix-shell-theme@jeronix   # back to the Ubuntu look\n"
          "  jeronix-layout plan /usr/share/jeronix/layouts/pure.json\n"
          "  dconf reset -f /org/gnome/   # forget your own changes, keep JERONIX defaults\n")

    # Normalize permissions: the image layer and .deb are root-owned.
    for p in root.rglob("*"):
        if p.is_dir():
            p.chmod(0o755)
        elif p.stat().st_mode & 0o111:
            p.chmod(0o755)
        else:
            p.chmod(0o644)
    root.chmod(0o755)
    return root


def build_deb(out, base_profile=None, maintainer=None):
    config = load_config()
    root = build_tree(out, base_profile)
    debian = root / "DEBIAN"
    debian.mkdir()
    size_kb = sum(p.stat().st_size for p in root.rglob("*") if p.is_file()) // 1024 + 1
    control = [
        f"Package: {config['package']}",
        f"Version: {config['version']}",
        "Architecture: all",
        f"Maintainer: {maintainer or git_maintainer()}",
        f"Installed-Size: {size_kb}",
        f"Depends: {', '.join(config['depends'])}",
        "Section: gnome",
        "Priority: optional",
        f"Description: {config['summary']}",
    ] + [f" {line}" if line else " ." for line in config["description"].splitlines()]
    (debian / "control").write_text("\n".join(control) + "\n", encoding="utf-8")
    conffiles = sorted("/" + str(p.relative_to(root)) for p in (root / "etc").rglob("*") if p.is_file())
    (debian / "conffiles").write_text("\n".join(conffiles) + "\n", encoding="utf-8")
    for p in debian.iterdir():
        p.chmod(0o644)
    deb = out / f"{config['package']}_{config['version']}_all.deb"
    subprocess.run(["dpkg-deb", "--root-owner-group", "-Zxz", "--build", str(root), str(deb)],
                   check=True, stdout=subprocess.DEVNULL)
    shutil.rmtree(debian)
    return deb


def git_maintainer():
    def git(key):
        r = subprocess.run(["git", "-C", str(ROOT), "config", key], capture_output=True, text=True)
        return r.stdout.strip()
    name, email = git("user.name"), git("user.email")
    return f"{name} <{email}>" if name and email else "JERONIX developers <noreply@localhost>"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the jeronix-desktop payload")
    ap.add_argument("what", choices=("tree", "deb"))
    ap.add_argument("out", type=Path)
    ap.add_argument("--dconf-profile", type=Path, help="the base image's /etc/dconf/profile/user, if any")
    args = ap.parse_args(argv)
    base = args.dconf_profile.read_text(encoding="utf-8") if args.dconf_profile else None
    args.out.mkdir(parents=True, exist_ok=True)
    result = build_tree(args.out, base) if args.what == "tree" else build_deb(args.out, base)
    print(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
